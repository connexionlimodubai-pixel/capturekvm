"""Generate wire and pairing test vectors from Beamer's real Python implementation.

The Android app speaks the same protocol as the Windows one, but by transcription rather than by
sharing code, and a single wrong byte in a key derivation means nothing ever pairs or links. So
the values that matter are computed here by the code that is known to work, written to a JSON
file, and asserted by the Kotlin unit tests.

    python tools/make_vectors.py

Writes android/app/src/test/resources/wire_vectors.json. Re-run it after changing the vendored
Beamer core, and run the Kotlin tests afterwards.
"""

import base64
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "beamer-vigem"))

from core import pairing, protocol  # noqa: E402  (needs the path above)

OUT = ROOT / "android" / "app" / "src" / "test" / "resources" / "wire_vectors.json"

# Fixed inputs. Nothing here is secret: they exist so both languages compute the same thing.
TOKEN = protocol.id_text(bytes(range(32)))
PREFIX_I = bytes.fromhex("0102030405060708")
PREFIX_R = bytes.fromhex("1112131415161718")
SECRET_I = bytes(range(32, 64))
SECRET_R = bytes(range(64, 96))
MACHINE_ID = bytes(range(16))
PEER_ID = bytes(range(16, 32))

PAIR_ID = "pair-vector-1"
NONCE = bytes.fromhex("000102030405060708090a0b0c0d0e0f")
CODE = "314159"
SCALAR_A = bytes(range(96, 128))
SCALAR_B = bytes(range(128, 160))


def hexed(data: bytes) -> str:
    return data.hex()


def beamer_revision() -> str:
    """Which `beamer-vigem` these vectors came from.

    Read from git rather than from a file written by hand: the subtree carries its own history, so
    the commit that last touched it is the honest answer and cannot go stale."""
    try:
        done = subprocess.run(
            ["git", "-C", str(ROOT), "log", "-1", "--format=%H", "--", "beamer-vigem"],
            capture_output=True, text=True, timeout=15, check=False,
        )
        revision = done.stdout.strip()
        if revision:
            return revision
    except (OSError, subprocess.SubprocessError):
        pass
    version = (ROOT / "beamer-vigem" / "VERSION")
    return f"unknown (Beamer {version.read_text().strip()})" if version.is_file() else "unknown"


def build() -> dict:
    vectors = {
        "note": "generated by tools/make_vectors.py from beamer-vigem",
        "beamer_revision": beamer_revision(),
        "beamer_version": (ROOT / "beamer-vigem" / "VERSION").read_text().strip(),
        "link_version": protocol.LINK_VERSION,
    }

    # --- b64, the one spelling PAIRING.md allows ---
    vectors["b64"] = [
        {"bytes": hexed(bytes(range(16))), "text": protocol.id_text(bytes(range(16)))},
        {"bytes": hexed(bytes(range(32))), "text": protocol.id_text(bytes(range(32)))},
        {"bytes": hexed(b"\xff\xfe\xfd"), "text": protocol.id_text(b"\xff\xfe\xfd")},
        {"bytes": hexed(b"\x00"), "text": protocol.id_text(b"\x00")},
        {"bytes": hexed(b""), "text": protocol.id_text(b"")},
    ]

    # --- HKDF and the key id ---
    vectors["hkdf"] = {
        "ikm": hexed(b"ikm bytes"),
        "salt": hexed(b"salt bytes"),
        "info": hexed(b"info bytes"),
        "out": hexed(protocol.hkdf_sha256(b"ikm bytes", b"salt bytes", b"info bytes")),
    }
    vectors["key_id"] = {"token": TOKEN, "out": hexed(protocol.key_id(TOKEN))}

    # --- X25519 ---
    share_i = protocol._x25519_shared.__globals__["crypto_scalarmult_base"](SECRET_I)
    share_r = protocol._x25519_shared.__globals__["crypto_scalarmult_base"](SECRET_R)
    shared = protocol._x25519_shared(SECRET_I, share_r)
    vectors["x25519"] = {
        "secret_i": hexed(SECRET_I),
        "share_i": hexed(share_i),
        "secret_r": hexed(SECRET_R),
        "share_r": hexed(share_r),
        "shared": hexed(shared),
    }

    # --- the link's info string and both direction keys ---
    key_id = protocol.key_id(TOKEN)
    vectors["link_info"] = {
        "out": hexed(protocol.link_info(key_id, PREFIX_I, PREFIX_R, share_i, share_r, 1)),
    }
    vectors["link_keys"] = {
        "token": TOKEN,
        "prefix_i": hexed(PREFIX_I),
        "prefix_r": hexed(PREFIX_R),
        "initiator": hexed(protocol.link_key(TOKEN, shared, key_id, PREFIX_I, PREFIX_R, share_i, share_r, 1)),
        "responder": hexed(protocol.link_key(TOKEN, shared, key_id, PREFIX_I, PREFIX_R, share_i, share_r, 2)),
    }

    # --- a whole handshake and the first two frames each way ---
    initiator = protocol.LinkSession(TOKEN, protocol.ROLE_INITIATOR, prefix=PREFIX_I, secret=SECRET_I)
    responder = protocol.LinkSession(TOKEN, protocol.ROLE_RESPONDER, prefix=PREFIX_R, secret=SECRET_R)
    initiator_preamble = initiator.preamble()
    responder.accept_preamble(initiator_preamble)
    responder_preamble = responder.preamble()
    initiator.accept_preamble(responder_preamble)

    first = b'{"type":"ping","data":{}}'
    second = b'{"type":"mousemove","data":{"dx":3,"dy":-4,"seq":1}}'
    sealed_first = initiator.seal_raw(first)
    sealed_second = initiator.seal_raw(second)
    from_responder = responder.seal_raw(b'{"type":"ack","data":{"seq":1,"held_us":120}}')

    vectors["handshake"] = {
        "token": TOKEN,
        "prefix_i": hexed(PREFIX_I),
        "secret_i": hexed(SECRET_I),
        "prefix_r": hexed(PREFIX_R),
        "secret_r": hexed(SECRET_R),
        "initiator_preamble": hexed(initiator_preamble),
        "responder_preamble": hexed(responder_preamble),
        "initiator_frames": [
            {"plain": first.decode(), "frame": hexed(sealed_first)},
            {"plain": second.decode(), "frame": hexed(sealed_second)},
        ],
        "responder_frame": {
            "plain": '{"type":"ack","data":{"seq":1,"held_us":120}}',
            "frame": hexed(from_responder),
        },
    }

    # --- CPace: the byte plumbing, the generator, a share and the agreed keys ---
    vectors["prepend_len"] = [
        {"bytes": hexed(b""), "out": hexed(pairing._prepend_len(b""))},
        {"bytes": hexed(b"abc"), "out": hexed(pairing._prepend_len(b"abc"))},
        {"bytes": hexed(b"x" * 200), "out": hexed(pairing._prepend_len(b"x" * 200))},
    ]
    vectors["lv_cat"] = {
        "parts": [hexed(b"one"), hexed(b""), hexed(b"three")],
        "out": hexed(pairing._lv_cat(b"one", b"", b"three")),
    }

    sid = pairing._session_id(PAIR_ID, NONCE)
    generator = pairing._generator(CODE.encode("utf-8"), pairing.CHANNEL_V3, sid)
    share_a = pairing._share(CODE, sid, SCALAR_A, pairing.CHANNEL_V3)
    share_b = pairing._share(CODE, sid, SCALAR_B, pairing.CHANNEL_V3)
    cpace_shared = pairing._x25519(SCALAR_A, share_b)

    requester = pairing._party(pairing.ROLE_REQUESTER, MACHINE_ID, "Tablet", "android", 0)
    host = pairing._party(pairing.ROLE_HOST, PEER_ID, "Desk PC", "windows", protocol.DEFAULT_PORT)
    token, requester_tag, host_tag, done_tag = pairing._keys(
        sid, cpace_shared, share_a, requester, share_b, host, pairing.TOKEN_INFO_V3
    )

    vectors["cpace"] = {
        "pair_id": PAIR_ID,
        "nonce": hexed(NONCE),
        "code": CODE,
        "sid": hexed(sid),
        "generator": hexed(generator),
        "scalar_a": hexed(SCALAR_A),
        "share_a": hexed(share_a),
        "scalar_b": hexed(SCALAR_B),
        "share_b": hexed(share_b),
        "shared": hexed(cpace_shared),
        "requester": {
            "id": hexed(MACHINE_ID), "name": "Tablet", "platform": "android", "port": 0,
            "ad": hexed(requester),
        },
        "host": {
            "id": hexed(PEER_ID), "name": "Desk PC", "platform": "windows",
            "port": protocol.DEFAULT_PORT, "ad": hexed(host),
        },
        "token": token,
        "requester_tag": hexed(requester_tag),
        "host_tag": hexed(host_tag),
        "done_tag": hexed(done_tag),
    }

    # --- elligator2 on its own, which is the one piece with no library to lean on ---
    vectors["elligator2"] = [
        {"r": str(value), "out": str(pairing._elligator2(value))}
        for value in (0, 1, 2, 3, 12345, 2 ** 200 + 7, 2 ** 255 - 20)
    ]

    return vectors


def main() -> int:
    vectors = build()
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(json.dumps(vectors, indent=2) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    print(f"  token under test: {vectors['cpace']['token']}")
    print(f"  beamer revision:  {vectors['beamer_revision']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
