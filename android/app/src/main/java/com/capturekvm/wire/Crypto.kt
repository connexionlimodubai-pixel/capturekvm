package com.capturekvm.wire

import java.math.BigInteger
import java.security.MessageDigest
import java.security.SecureRandom
import javax.crypto.Mac
import javax.crypto.spec.SecretKeySpec
import org.bouncycastle.crypto.modes.ChaCha20Poly1305
import org.bouncycastle.crypto.params.AEADParameters
import org.bouncycastle.crypto.params.KeyParameter
import org.bouncycastle.math.ec.rfc7748.X25519

/**
 * The primitives Beamer's wire and pairing are built from, matched to what the Python side uses:
 * libsodium's X25519 and IETF ChaCha20-Poly1305, HKDF-SHA256 cut to one block, and SHA-512 with
 * HMAC-SHA512 for CPace.
 *
 * BouncyCastle rather than the platform: `KeyAgreement("XDH")` is API 33 and up, and the
 * `ChaCha20-Poly1305` cipher is API 28 and up, so neither is reachable on the phones this app
 * supports. `Vectors` in the unit tests checks every function here against values generated by
 * the real Python implementation.
 */
object Crypto {

    private val random = SecureRandom()

    const val SHARE_SIZE = 32
    const val TAG_SIZE = 16

    class CryptoRefused(message: String) : Exception(message)

    fun randomBytes(size: Int): ByteArray = ByteArray(size).also(random::nextBytes)

    // --- hashes ---

    fun sha512(vararg parts: ByteArray): ByteArray {
        val digest = MessageDigest.getInstance("SHA-512")
        parts.forEach(digest::update)
        return digest.digest()
    }

    fun hmacSha512(key: ByteArray, message: ByteArray): ByteArray =
        mac("HmacSHA512", key, message)

    fun hmacSha256(key: ByteArray, message: ByteArray): ByteArray =
        mac("HmacSHA256", key, message)

    private fun mac(algorithm: String, key: ByteArray, message: ByteArray): ByteArray {
        val mac = Mac.getInstance(algorithm)
        // An all-zero or empty key is legal for HMAC and SecretKeySpec rejects empty, so a
        // zero-length salt becomes one zero byte, exactly as HKDF's extract step defines it.
        mac.init(SecretKeySpec(if (key.isEmpty()) ByteArray(1) else key, algorithm))
        return mac.doFinal(message)
    }

    /**
     * HKDF-SHA256 for one 32-byte block, which is the only length the link needs. Mirrors
     * `core.protocol.hkdf_sha256`: extract with the salt as the HMAC key, then one expand round
     * over `info || 0x01`.
     */
    fun hkdfSha256(keyMaterial: ByteArray, salt: ByteArray, info: ByteArray): ByteArray {
        val extracted = hmacSha256(salt, keyMaterial)
        return hmacSha256(extracted, info + byteArrayOf(1))
    }

    // --- X25519 ---

    fun x25519Base(scalar: ByteArray): ByteArray {
        require(scalar.size == SHARE_SIZE) { "an X25519 scalar is 32 bytes" }
        val out = ByteArray(SHARE_SIZE)
        X25519.scalarMultBase(scalar, 0, out, 0)
        return out
    }

    /**
     * X25519 that refuses the neutral element, which is what libsodium's `crypto_scalarmult`
     * reports as an error and what CPace's `scalar_mult_vfy` must abort on.
     */
    fun x25519(scalar: ByteArray, point: ByteArray): ByteArray {
        require(scalar.size == SHARE_SIZE) { "an X25519 scalar is 32 bytes" }
        if (point.size != SHARE_SIZE) throw CryptoRefused("an X25519 point is 32 bytes")
        val out = ByteArray(SHARE_SIZE)
        X25519.scalarMult(scalar, 0, point, 0, out, 0)
        // BouncyCastle's scalarMult returns nothing, so the all-zero check is the whole test --
        // which is what the Python relies on too: every low-order share gives zeros and nothing
        // else does.
        if (out.all { it == 0.toByte() }) throw CryptoRefused("the X25519 result is the neutral element")
        return out
    }

    // --- AEAD ---

    fun seal(key: ByteArray, nonce: ByteArray, plaintext: ByteArray): ByteArray =
        aead(true, key, nonce, plaintext)

    fun open(key: ByteArray, nonce: ByteArray, sealed: ByteArray): ByteArray {
        if (sealed.size < TAG_SIZE) throw CryptoRefused("shorter than a tag")
        return aead(false, key, nonce, sealed)
    }

    private fun aead(sealing: Boolean, key: ByteArray, nonce: ByteArray, input: ByteArray): ByteArray {
        require(key.size == 32) { "a ChaCha20-Poly1305 key is 32 bytes" }
        require(nonce.size == 12) { "an IETF ChaCha20-Poly1305 nonce is 12 bytes" }
        val cipher = ChaCha20Poly1305()
        cipher.init(sealing, AEADParameters(KeyParameter(key), TAG_SIZE * 8, nonce))
        val out = ByteArray(cipher.getOutputSize(input.size))
        var written = cipher.processBytes(input, 0, input.size, out, 0)
        written += try {
            cipher.doFinal(out, written)
        } catch (exc: Exception) {
            throw CryptoRefused("the frame's tag did not check out")
        }
        return if (written == out.size) out else out.copyOf(written)
    }

    fun constantTimeEquals(left: ByteArray, right: ByteArray): Boolean {
        if (left.size != right.size) return false
        var difference = 0
        for (index in left.indices) difference = difference or (left[index].toInt() xor right[index].toInt())
        return difference == 0
    }

    // --- CPace's Elligator 2 ---

    private val FIELD_PRIME: BigInteger = BigInteger.TWO.pow(255).subtract(BigInteger.valueOf(19))
    private val CURVE_A: BigInteger = BigInteger.valueOf(486662)

    /**
     * The u coordinate Elligator 2 maps a field element to on Curve25519 (RFC 9380 6.7.1 with
     * Z = 2). A direct transcription of `core.pairing._elligator2`, because the two must agree
     * bit for bit or no code ever pairs.
     */
    fun elligator2(r: BigInteger): BigInteger {
        val p = FIELD_PRIME
        val one = BigInteger.ONE
        val denominator = one.add(BigInteger.TWO.multiply(r).multiply(r)).mod(p)
        val v = CURVE_A.negate().multiply(denominator.modPow(p.subtract(BigInteger.TWO), p)).mod(p)
        val inner = v.multiply(v).multiply(v)
            .add(CURVE_A.multiply(v).multiply(v))
            .add(v)
            .mod(p)
        val isSquare = inner.modPow(p.subtract(one).divide(BigInteger.TWO), p) == one
        return if (isSquare) v else v.negate().subtract(CURVE_A).mod(p)
    }

    fun littleEndian(value: BigInteger, size: Int): ByteArray {
        val out = ByteArray(size)
        var work = value
        val mask = BigInteger.valueOf(0xFF)
        for (index in 0 until size) {
            out[index] = work.and(mask).toInt().toByte()
            work = work.shiftRight(8)
        }
        return out
    }

    fun fromLittleEndian(bytes: ByteArray): BigInteger {
        var value = BigInteger.ZERO
        for (index in bytes.indices.reversed()) {
            value = value.shiftLeft(8).or(BigInteger.valueOf((bytes[index].toInt() and 0xFF).toLong()))
        }
        return value
    }
}
